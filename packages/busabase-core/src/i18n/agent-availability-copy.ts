export const agentAvailabilityCopy = (locale: CoreLocale): AvailabilityCopy => {
  if (locale === "en") return en;
  return Object.fromEntries(
    Object.keys(en).map((key, index) => [key, translations[locale][index]]),
  ) as AvailabilityCopy;
};
