/** Kept separate from the large dashboard catalogs, like Router enrollment. */
export const agentConnectionCopy = (locale: CoreLocale): typeof en => {
  if (locale === "en") return en;
  if (locale === "zh-CN") return zhCN;
  const values = translations[locale];
  return Object.fromEntries(
    Object.entries(en).map(([key, fallback], index) => [key, values[index] ?? fallback]),
  ) as typeof en;
};
